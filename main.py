def safe_str(
    value: Any,
    fallback: str = "N/A",
) -> str:

    if value is None:
        return fallback

    text = str(value).strip()

    if not text:
        return fallback

    return text


def safe_float(
    value: Any,
) -> Optional[float]:

    try:

        if value is None:
            return None

        number = float(value)

        if number != number:
            return None

        return number

    except (
        TypeError,
        ValueError,
    ):

        return None


