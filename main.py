# SPEED TEST
# ============================================================

@app.get(
    f"/api/{API_VERSION}/speed-test"
)
async def speed_test():

    global LAST_SPEED_TEST

    started = time.perf_counter()

    target_host = "1.1.1.1"

    target_port = 443

    latency = measure_latency(
        target_host,
        target_port,
        attempts=3,
    )

    internet = (
        latency is not None
    )

    elapsed = (
        time.perf_counter()
        - started
    ) * 1000

    result = {
        "status":
            "COMPLETED"
            if internet
            else "FAILED",

        "server":
            f"{target_host}:{target_port}",

        "latency_ms":
            latency,

        # ----------------------------------------------------
        # Deliberately NOT fabricated.
        # Full throughput measurement requires a proper
        # download/upload test implementation.
        # ----------------------------------------------------

        "download_mbps":
            None,

        "upload_mbps":
            None,

        "download_speed":
            None,

        "upload_speed":
            None,

        "internet":
            internet,

        "test_duration_ms":
            round(
                elapsed,
                2,
            ),

        "message":
            (
                "Connection benchmark completed. "
                "Full download/upload throughput "
                "measurement is not enabled yet."
                if internet
                else
                "Connection benchmark failed."
            ),

        "timestamp":
            utc_now(),
    }

    LAST_SPEED_TEST = result

    if DATABASE_AVAILABLE:

        try:

            save_speed_test(
                result
            )

        except Exception as error:

            print(
                "Could not save speed test:",
                error,
            )

    return result


