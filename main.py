def check_internet(
    host: str = "1.1.1.1",
    port: int = 443,
    timeout: float = 3.0,
) -> bool:

    try:

        sock = socket.create_connection(
            (
                host,
                port,
            ),
            timeout=timeout,
        )

        sock.close()

        return True

    except Exception:

        return False


# ============================================================
# TCP LATENCY
# ============================================================

def measure_latency(
    host: str = "1.1.1.1",
    port: int = 443,
    attempts: int = 3,
) -> Optional[float]:

    measurements: list[float] = []

    for _ in range(attempts):

        started = time.perf_counter()

        try:

            sock = socket.create_connection(
                (
                    host,
                    port,
                ),
                timeout=3,
            )

            sock.close()

            elapsed = (
                time.perf_counter()
                - started
            ) * 1000

            measurements.append(
                elapsed
            )

        except Exception:

            continue

    if not measurements:
        return None

    return statistics.mean(
        measurements
    )


# ============================================================
# JITTER
# ============================================================

def measure_jitter(
    host: str = "1.1.1.1",
    port: int = 443,
    attempts: int = 5,
) -> Optional[float]:

    measurements: list[float] = []

    for _ in range(attempts):

        latency = measure_latency(
            host,
            port,
            attempts=1,
        )

        if latency is not None:

            measurements.append(
                latency
            )

        time.sleep(0.05)

    if len(measurements) < 2:

        return None

    differences = [
        abs(
            measurements[i]
            - measurements[i - 1]
        )
        for i in range(
            1,
            len(measurements),
        )
    ]

    return statistics.mean(
        differences
    )


# ============================================================
# NETWORK SCORE
# ============================================================

def calculate_network_score(
    latency: Optional[float],
    jitter: Optional[float],
    packet_loss: Optional[float],
    internet: bool,
) -> dict[str, Any]:

    if not internet:

        return {
            "score": 0,
            "quality": "CRITICAL",
            "description": (
                "Internet connectivity is unavailable."
            ),
        }

    score = 100.0

    # Latency
    if latency is None:

        score -= 25

    elif latency <= 40:

        score -= 0

    elif latency <= 80:

        score -= 10

    elif latency <= 150:

        score -= 20

    elif latency <= 300:

        score -= 35

    else:

        score -= 50

    # Jitter
    if jitter is not None:

        if jitter <= 10:
            score -= 0

        elif jitter <= 30:
            score -= 5

        elif jitter <= 60:
            score -= 10

        else:
            score -= 20

    # Packet loss
    if packet_loss is not None:

        if packet_loss <= 1:
            score -= 0

        elif packet_loss <= 5:
            score -= 10

        elif packet_loss <= 10:
            score -= 20

        else:
            score -= 35

    score = max(
        0,
        min(
            100,
            round(score),
        ),
    )

    if score >= 90:

        quality = "EXCELLENT"

    elif score >= 75:

        quality = "GOOD"

    elif score >= 50:

        quality = "FAIR"

    elif score >= 25:

        quality = "POOR"

    else:

        quality = "CRITICAL"

    return {
        "score": score,
        "quality": quality,
        "description": (
            f"Network quality is {quality.lower()}."
        ),
    }


# ============================================================
# INTELLIGENCE RECOMMENDATION
# ============================================================

def generate_intelligence(
    score: int,
    latency: Optional[float],
    jitter: Optional[float],
    packet_loss: Optional[float],
) -> dict[str, str]:

    if score >= 90:

        return {
            "priority": "LOW",
            "action": "Maintain connection",
            "message": (
                "Current network conditions are strong."
            ),
        }

    if score >= 75:

        return {
            "priority": "NORMAL",
            "action": "Continue monitoring",
            "message": (
                "The connection is stable."
            ),
        }

    if score >= 50:

        return {
            "priority": "MEDIUM",
            "action": "Monitor performance",
            "message": (
                "Network quality is moderate."
            ),
        }

    if score >= 25:

        return {
            "priority": "HIGH",
            "action": "Consider network switch",
            "message": (
                "A better available connection "
                "may improve performance."
            ),
        }

    return {
        "priority": "CRITICAL",
        "action": "Check connectivity",
        "message": (
            "Network conditions require immediate attention."
        ),
    }


