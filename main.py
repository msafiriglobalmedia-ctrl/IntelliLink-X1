# ============================================================

@app.get(
    f"/api/{API_VERSION}/diagnostics"
)
async def diagnostics():

    global LAST_DIAGNOSTICS

    platform_info = get_platform_info()

    interface = get_network_interface()

    gateway = get_default_gateway()

    internet = check_internet()

    python_version = (
        platform_info[
            "python_version"
        ]
    )

    if internet:

        status = "PASS"

    else:

        status = "WARNING"

    diagnostics_data = {
        "status": status,

        "python": python_version,

        "python_version":
            python_version,

        "interface":
            interface,

        "network_interface":
            interface,

        "gateway":
            gateway,

        "default_gateway":
            gateway,

        "internet":
            "PASS"
            if internet
            else "FAIL",

        "internet_status":
            internet,

        "platform":
            platform_info,

        "message":
            (
                "Diagnostics completed successfully."
                if internet
                else
                "Diagnostics completed, but internet "
                "connectivity is unavailable."
            ),

        "timestamp": utc_now(),
    }

    LAST_DIAGNOSTICS = diagnostics_data

    if DATABASE_AVAILABLE:

        try:

            save_diagnostic(
                diagnostics_data
            )

        except Exception as error:

            print(
                "Could not save diagnostic:",
                error,
            )

    return diagnostics_data


