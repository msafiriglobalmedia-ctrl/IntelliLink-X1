@app.get(
    f"/api/{API_VERSION}/status"
)
async def application_status():

    device = None

    if DATABASE_AVAILABLE:

        try:

            device = get_device()

        except Exception:

            device = None

    network = (
        LAST_NETWORK_SNAPSHOT
        or collect_network_snapshot()
    )

    return {
        "application": APP_NAME,

        "version": APP_VERSION,

        "status": "RUNNING",

        "uptime_seconds":
            round(
                time.time()
                - START_TIME,
                2,
            ),

        "database_available":
            DATABASE_AVAILABLE,

        "device_id":
            device.get(
                "device_id"
            )
            if device
            else None,

        "network_score":
            network.get(
                "score"
            ),

        "network_quality":
            network.get(
                "quality"
            ),

        "internet":
            network.get(
                "internet"
            ),

        "timestamp": utc_now(),
    }


