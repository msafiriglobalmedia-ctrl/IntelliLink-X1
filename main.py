@app.get(
    f"/api/{API_VERSION}/network/score"
)
async def network_score():

    if LAST_NETWORK_SNAPSHOT:

        snapshot = LAST_NETWORK_SNAPSHOT

    else:

        snapshot = collect_network_snapshot()

    score = snapshot.get(
        "score"
    )

    quality = snapshot.get(
        "quality"
    )

    intelligence = snapshot.get(
        "intelligence"
    )

    return {
        "score": score,

        "quality": quality,

        "description":
            snapshot.get(
                "score_description"
            ),

        "intelligence":
            intelligence,

        "latency_ms":
            snapshot.get(
                "latency_ms"
            ),

        "jitter_ms":
            snapshot.get(
                "jitter_ms"
            ),

        "packet_loss_percent":
            snapshot.get(
                "packet_loss_percent"
            ),

        "timestamp":
            snapshot.get(
                "timestamp",
                utc_now(),
            ),
    }


