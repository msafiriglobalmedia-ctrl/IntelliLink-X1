# NETWORK SNAPSHOT
# ============================================================

def collect_network_snapshot() -> dict[str, Any]:

    started = time.perf_counter()

    hostname = get_hostname()

    local_ip = get_local_ip()

    gateway = get_default_gateway()

    interface = get_network_interface()

    connection_type = detect_connection_type()

    wifi = get_wifi_info()

    internet = check_internet()

    latency = None
    jitter = None

    if internet:

        latency = measure_latency()

        jitter = measure_jitter()

    packet_loss = None

    score_data = calculate_network_score(
        latency=latency,
        jitter=jitter,
        packet_loss=packet_loss,
        internet=internet,
    )

    intelligence = generate_intelligence(
        score=score_data["score"],
        latency=latency,
        jitter=jitter,
        packet_loss=packet_loss,
    )

    elapsed = (
        time.perf_counter()
        - started
    ) * 1000

    snapshot = {
        "timestamp": utc_now(),

        "hostname": hostname,

        "local_ip": local_ip,

        "gateway": gateway,

        "interface": interface,

        "connection_type": connection_type,

        "internet": internet,

        "wifi": wifi,

        "latency_ms": latency,

        "jitter_ms": jitter,

        "packet_loss_percent": packet_loss,

        "signal": wifi.get("signal"),

        "download_mbps": None,

        "upload_mbps": None,

        "score": score_data["score"],

        "quality": score_data["quality"],

        "score_description":
            score_data["description"],

        "intelligence": intelligence,

        "collection_time_ms":
            round(elapsed, 2),
    }

    return snapshot


