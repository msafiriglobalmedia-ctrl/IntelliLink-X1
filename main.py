# LOCAL IP
# ============================================================

def get_local_ip() -> Optional[str]:

    sock = None

    try:

        sock = socket.socket(
            socket.AF_INET,
            socket.SOCK_DGRAM,
        )

        sock.settimeout(1)

        sock.connect(
            (
                "8.8.8.8",
                80,
            )
        )

        return sock.getsockname()[0]

    except Exception:

        return None

    finally:

        if sock:

            try:
                sock.close()
            except Exception:
                pass


# ============================================================
# DEFAULT GATEWAY
# ============================================================

def get_default_gateway() -> Optional[str]:

    system = platform.system().lower()

    try:

        if system == "windows":

            result = subprocess.run(
                [
                    "route",
                    "print",
                    "0.0.0.0",
                ],
                capture_output=True,
                text=True,
                timeout=3,
            )

            for line in result.stdout.splitlines():

                parts = line.split()

                if (
                    len(parts) >= 3
                    and parts[0] == "0.0.0.0"
                ):

                    return parts[2]

        else:

            result = subprocess.run(
                [
                    "ip",
                    "route",
                ],
                capture_output=True,
                text=True,
                timeout=3,
            )

            for line in result.stdout.splitlines():

                parts = line.split()

                if (
                    len(parts) >= 3
                    and parts[0] == "default"
                    and parts[1] == "via"
                ):

                    return parts[2]

    except Exception:

        pass

    return None


# ============================================================
# NETWORK INTERFACE
# ============================================================

def get_network_interface() -> Optional[str]:

    system = platform.system().lower()

    try:

        if system == "windows":

            result = subprocess.run(
                [
                    "ipconfig",
                ],
                capture_output=True,
                text=True,
                timeout=3,
            )

            if result.returncode == 0:
                return "Windows Network Interface"

        else:

            result = subprocess.run(
                [
                    "ip",
                    "route",
                    "get",
                    "8.8.8.8",
                ],
                capture_output=True,
                text=True,
                timeout=3,
            )

            output = result.stdout.strip()

            parts = output.split()

            if "dev" in parts:

                index = parts.index("dev")

                if index + 1 < len(parts):

                    return parts[index + 1]

    except Exception:

        pass

    return None


# ============================================================
# CONNECTION TYPE
# ============================================================

def detect_connection_type() -> str:

    interface = get_network_interface()

    if not interface:

        return "UNKNOWN"

    name = interface.lower()

    if (
        "wlan" in name
        or "wifi" in name
        or name.startswith("wl")
    ):

        return "Wi-Fi"

    if (
        "eth" in name
        or "en" in name
        or "ethernet" in name
    ):

        return "Ethernet"

    if (
        "wwan" in name
        or "cell" in name
        or "rmnet" in name
    ):

        return "Cellular"

    return "NETWORK"


# ============================================================
# WIFI INFORMATION
# ============================================================

def get_wifi_info() -> dict[str, Any]:

    system = platform.system().lower()

    result: dict[str, Any] = {
        "available": False,
        "connected": False,
        "ssid": None,
        "signal": None,
        "status": "Unavailable",
        "interface": None,
        "note": None,
    }

    interface = get_network_interface()

    result["interface"] = interface

    connection_type = detect_connection_type()

    if connection_type == "Wi-Fi":

        result["available"] = True
        result["connected"] = True
        result["status"] = "Connected"

    else:

        result["status"] = "Not detected"

    # --------------------------------------------------------
    # Windows Wi-Fi
    # --------------------------------------------------------

    if system == "windows":

        try:

            output = subprocess.run(
                [
                    "netsh",
                    "wlan",
                    "show",
                    "interfaces",
                ],
                capture_output=True,
                text=True,
                timeout=4,
            ).stdout

            for line in output.splitlines():

                clean = line.strip()

                if clean.startswith("SSID"):

                    if ":" in clean:

                        result["ssid"] = (
                            clean.split(":", 1)[1]
                            .strip()
                        )

                elif clean.startswith("Signal"):

                    if ":" in clean:

                        signal_text = (
                            clean.split(":", 1)[1]
                            .strip()
                        )

                        result["signal"] = signal_text

                elif clean.startswith("State"):

                    if ":" in clean:

                        state = (
                            clean.split(":", 1)[1]
                            .strip()
                            .lower()
                        )

                        result["connected"] = (
                            state == "connected"
                        )

        except Exception:

            pass

    # --------------------------------------------------------
    # Linux Wi-Fi
    # --------------------------------------------------------

    elif system == "linux":

        try:

            output = subprocess.run(
                [
                    "iwgetid",
                    "-r",
                ],
                capture_output=True,
                text=True,
                timeout=3,
            ).stdout.strip()

            if output:

                result["ssid"] = output
                result["available"] = True
                result["connected"] = True
                result["status"] = "Connected"

        except Exception:

            pass

    # --------------------------------------------------------
    # Android / Termux / Pydroid
    # --------------------------------------------------------

    if (
        not result["ssid"]
        and "android" in platform.platform().lower()
    ):

        result["note"] = (
            "Android may restrict Wi-Fi information "
            "without native system permissions."
        )

    return result


