@app.get(
    f"/api/{API_VERSION}/database/health"
)
async def database_health_endpoint():

    if not DATABASE_AVAILABLE:

        return {
            "status": "UNAVAILABLE",

            "available": False,

            "error":
                DATABASE_IMPORT_ERROR,
        }

    try:

        result = database_health()

        return {
            "available": True,

            **(
                result
                if isinstance(
                    result,
                    dict,
                )
                else {
                    "status":
                        str(result)
                }
            ),
        }

    except Exception as error:

        return {
            "available": False,

            "status": "ERROR",

            "error": str(error),
        }


